// Writes apps/mobile/.env.local for real auth against the LOCAL Supabase stack:
// the provider switch and the stack's publishable (public) key. Reads the key
// from `supabase status`; never writes a secret key. Run from the repo root:
//   pnpm --filter @voya/mobile env:local
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const raw = execFileSync('pnpm', ['--filter', '@voya/api', 'exec', 'supabase', 'status', '-o', 'json'], {
  cwd: join(here, '..', '..', '..'),
  encoding: 'utf8',
  stdio: ['ignore', 'pipe', 'ignore'],
});
const status = JSON.parse(raw.slice(raw.indexOf('{')));
const key = status.PUBLISHABLE_KEY ?? status.ANON_KEY;
if (!key || key.startsWith('sb_secret_')) {
  console.error('Local Supabase is not running (pnpm --filter @voya/api supabase:start).');
  process.exit(1);
}
const target = join(here, '..', '.env.local');
writeFileSync(
  target,
  ['# Generated by scripts/write-local-env.mjs — local stack only, public key only.', 'EXPO_PUBLIC_VOYA_AUTH=supabase', `EXPO_PUBLIC_SUPABASE_KEY=${key}`, ''].join('\n'),
);
console.log(`Wrote ${target} (real auth on; restart Metro with --clear to pick it up).`);
